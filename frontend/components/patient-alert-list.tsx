"use client";

import { useEffect, useState } from "react";
import { api } from "../lib/api/client";
import type { Alert } from "../lib/api/generated";
import { getSession } from "../lib/auth/session";
import { Icon } from "./icon";

export function PatientAlertList() {
  const [alerts, setAlerts] = useState<Alert[]>([]);
  const [error, setError] = useState(""); const [loading, setLoading] = useState(true);
  useEffect(() => {
    const session = getSession(); if (!session) return;
    let cancelled = false;
    void api.alerts(session.accessToken).then((result) => { if (!cancelled) setAlerts(result); }).catch(() => { if (!cancelled) setError("Alerts could not be refreshed. Please return to this page to try again."); }).finally(() => { if (!cancelled) setLoading(false); });
    return () => { cancelled = true; };
  }, []);
  return <section className="card"><div className="workspace-section-head"><div><h2>Recorded alert status</h2><p>Demo alerts generated by deterministic server rules.</p></div><span className="count-badge">{loading ? "Loading" : `${alerts.length} recorded`}</span></div>
    {loading ? <p role="status" className="loading-copy">Loading your alerts…</p> : error ? <p role="alert" className="form-error">{error}</p> : alerts.length ? alerts.map((alert) => <article key={alert.id} className="alert-record"><div className="alert-record-header"><span className={`status-badge ${alert.severity}`}>{alert.severity}</span><strong>{alert.rule_code.replaceAll("_", " ")}</strong><span className={`status-badge ${alert.status}`}>{alert.status}</span></div><p>{alert.guidance}</p><p><time dateTime={alert.created_at}>{new Date(alert.created_at).toLocaleString()}</time></p></article>) : <div className="empty-state"><Icon name="bell" /><h3>No alerts to show</h3><p>No server-supplied alerts are available for your account.</p></div>}
    <p className="history-chart-note">This app is not an emergency service. Do not wait for a response from this app in an emergency.</p>
  </section>;
}
